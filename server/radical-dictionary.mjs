export function toCanonicalRadicalGlyph(glyph) {
  if (!glyph) return ''
  const trimmed = String(glyph).trim()
  if (!trimmed) return ''
  const mapped = canonicalMap[trimmed] || KANGXI_TO_STANDARD_EXTRA[trimmed]
  if (mapped) return mapped
  // Normalize Kangxi Radicals Unicode block (U+2F00..U+2FD5) via NFKC to standard CJK unified ideograph
  if (/^[\u2f00-\u2fd5]$/u.test(trimmed)) {
    const nfkc = trimmed.normalize('NFKC')
    return KANGXI_TO_STANDARD_EXTRA[nfkc] || nfkc
  }
  return trimmed
}

export function toRadicalFamilyGlyph(glyph) {
  const canon = toCanonicalRadicalGlyph(glyph)
  if (!canon) return ''
  return RADICAL_VARIANT_TO_FAMILY[canon] || canon
}

export function getRadicalMetadata(glyph) {
  const family = toRadicalFamilyGlyph(glyph)
  if (!family) return { family: '', nameVi: '', strokeCount: 0 }
  const meta = RADICAL_META[family]
  if (meta) return { family, nameVi: meta.nameVi, strokeCount: meta.strokeCount }
  return { family, nameVi: '', strokeCount: 0 }
}

