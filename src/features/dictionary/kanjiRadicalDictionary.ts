/**
 * Normalizes any Kangxi / CJK Supplement radical glyph to standard unified CJK form.
 * E.g. '⺅' -> '亻', '⼞' -> '囗', '⽇' -> '日', '⾨' -> '門'
 */
export function toCanonicalRadicalGlyph(glyph?: string): string {
  if (!glyph) return ''
  const trimmed = glyph.trim()
  if (!trimmed) return ''
  return CANONICAL_RADICAL_GLYPHS[trimmed] || trimmed
}

/**
 * Translates an English or raw radical meaning into refined Vietnamese.
 * Guaranteed: zero English phrases will pass through.
 */
export function translateRadicalMeaning(meaning?: string, radicalChar?: string): string {
  if (!meaning && !radicalChar) return 'Bộ thủ biểu ý cốt lõi'
  
  const raw = (meaning || '').trim()
  
  // 1. Direct match with English phrase database
  if (raw && RADICAL_ENGLISH_TO_VIETNAMESE[raw]) {
    return RADICAL_ENGLISH_TO_VIETNAMESE[raw]
  }

  // 2. Case-insensitive lookup for English phrases
  if (raw && /[a-zA-Z]{2,}/.test(raw)) {
    const lower = raw.toLowerCase()
    for (const [enKey, viVal] of Object.entries(RADICAL_ENGLISH_TO_VIETNAMESE)) {
      if (enKey.toLowerCase() === lower) {
        return viVal
      }
    }
  }

  // 3. Fallback to canonical radical glyph metadata
  if (radicalChar) {
    const canon = toCanonicalRadicalGlyph(radicalChar)
    if (RADICAL_METADATA_VI[canon]?.meaning) {
      return RADICAL_METADATA_VI[canon].meaning
    }
    if (RADICAL_METADATA_VI[radicalChar]?.meaning) {
      return RADICAL_METADATA_VI[radicalChar].meaning
    }
  }

  // 4. If raw is already Vietnamese (contains Vietnamese diacritics or non-ascii, or has no Latin words)
  if (raw && (!/[a-zA-Z]{3,}/.test(raw) || /[àáảãạăằắẳẵặâầấẩẫậèéẻẽẹêềếểễệìíỉĩịòóỏõọôồốổỗộơờớởỡợùúủũụưừứửữựỳýỷỹỵđ]/i.test(raw))) {
    return raw
  }

  return 'Bộ thủ biểu ý cốt lõi'
}

/**
 * Gets the Hán-Việt name of a radical, guaranteed in Vietnamese.
 */
export function getRadicalVietnameseName(radicalChar: string, fallbackName?: string): string {
  const canon = toCanonicalRadicalGlyph(radicalChar)
  if (RADICAL_METADATA_VI[canon]?.name) {
    return RADICAL_METADATA_VI[canon].name
  }
  if (RADICAL_METADATA_VI[radicalChar]?.name) {
    return RADICAL_METADATA_VI[radicalChar].name
  }
  if (fallbackName && !/[a-zA-Z]{3,}/.test(fallbackName)) {
    return fallbackName
  }
  return canon || radicalChar
}

/**
 * Returns full Vietnamese metadata for a radical.
 */
export function getRadicalVietnameseInfo(radicalChar: string, rawMeaning?: string): {
  glyph: string
  canonicalGlyph: string
  name: string
  meaning: string
} {
  const canonicalGlyph = toCanonicalRadicalGlyph(radicalChar)
  const name = getRadicalVietnameseName(radicalChar)
  const meaning = translateRadicalMeaning(rawMeaning, canonicalGlyph)
  return {
    glyph: radicalChar,
    canonicalGlyph,
    name,
    meaning,
  }
}
